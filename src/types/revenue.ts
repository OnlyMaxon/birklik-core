/**
 * Выручка площадки за месяц.
 *
 * Документ коллекции `revenue`, имя документа — сам месяц: `2026-11`. Собирает
 * его триггер `recordRevenue` в функциях по журналу платежей `payments`; из
 * браузера и из приложения эта коллекция ТОЛЬКО читается, и то лишь
 * модератором — запись закрыта правилами всем без исключения.
 *
 * Месяц считается по бакинскому времени (UTC+4), а не по UTC: платёж в 02:00
 * первого декабря по Баку случается тридцатого ноября по UTC, и попасть он
 * должен в декабрь — туда же, куда попадёт в банковской выписке.
 *
 * ⚠️ Почти все поля НЕОБЯЗАТЕЛЬНЫЕ, и это не небрежность. Документ собирается
 * прибавками (`FieldValue.increment`) по мере покупок, и поле заводится в тот
 * миг, когда появляется первая покупка такого рода. В месяце без единого
 * подъёма поля `byKindAzn.boost` НЕ БУДЕТ вовсе — не ноль, а отсутствие.
 * Читающий обязан это учитывать, иначе получит `undefined` там, где ждал
 * число.
 */

/** Касса, через которую пришли деньги. */
export type RevenueProvider = 'azericard' | 'app_store' | 'google_play'

/** Что куплено: платный тариф или пакет подъёмов. */
export type RevenueKind = 'tier' | 'boost'

export interface MonthlyRevenue {
  /** Сам месяц, `2026-11`. Дублирует имя документа — удобно при выборках. */
  month: string

  /**
   * Итог месяца в манатах.
   *
   * ⚠️ Это БРУТТО: столько заплатили покупатели. Apple и Google удерживают
   * свою долю (15% при нашем обороте), и на счёт придёт меньше. Показывая это
   * число, обязательно показывать и оговорку — `moderation.revenueGrossNote`.
   */
  grossAzn?: number

  /**
   * Сколько заплачено в каждой валюте, как есть: `{AZN: 75, USD: 10}`.
   *
   * Долларовые суммы входят и сюда, и в `grossAzn` — там по курсу `usdRate`.
   * Валюта, курса которой у нас нет, попадает только сюда, а в итог манатами
   * НЕ входит; сколько таких покупок, говорит `unconvertedCount`.
   */
  gross?: Partial<Record<string, number>>

  /** Выручка манатами по кассам. */
  byProviderAzn?: Partial<Record<RevenueProvider, number>>

  /** Число покупок по кассам. */
  countByProvider?: Partial<Record<RevenueProvider, number>>

  /** Выручка манатами по виду товара. */
  byKindAzn?: Partial<Record<RevenueKind, number>>

  /** Всего покупок за месяц — включая те, у которых суммы нет. */
  count?: number

  /**
   * Сколько покупок посчитано по нашему прейскуранту, а не по чеку.
   *
   * У ответа Google по чеку цены нет вовсе — это свойство их API. Для
   * азербайджанской витрины числа совпадают с настоящими, для чужой это
   * оценка.
   */
  estimatedCount?: number

  /** Покупки в валюте без курса: в `gross` они есть, в `grossAzn` их нет. */
  unconvertedCount?: number

  /** Покупки, у которых суммы нет ниоткуда. Учтены только в `count`. */
  missingAmountCount?: number

  /**
   * Возвращено покупателям, манатами, — и возврат попадает в ТОТ месяц, в
   * котором покупка была заработана, а не в месяц самого возврата. Иначе
   * прошлый месяц навсегда остался бы завышен.
   *
   * ⚠️ Считаются только возвраты МАГАЗИНОВ. Возврат из кабинета банка до нас
   * не доходит — Azericard о нём не извещает.
   */
  refundedAzn?: number
  refundCount?: number

  /** Курс доллара, по которому посчитан этот месяц. */
  usdRate?: number

  updatedAt?: unknown
}
