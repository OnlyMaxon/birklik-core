/**
 * Месяц по бакинскому времени, вид `2026-11`.
 *
 * ⚠️ **Границу месяца надо считать ТАК ЖЕ, как её считает сервер**, иначе отчёт
 * и счётчик оплат разойдутся на сутки. Оплата в 02:00 первого декабря по Баку —
 * это 30 ноября по UTC: `toISOString().slice(0, 7)` отнёс бы её в ноябрь, а
 * счётчик выручки уже записал в декабрь. В отчёте за ноябрь сумма оплат тогда
 * не сошлась бы ни с одним списком, и понять, который из двух врёт, со стороны
 * было бы нельзя.
 *
 * ⚠️ **Такая же функция лежит в `firebase-functions/src/revenue/record-revenue.ts`.**
 * Копии две не от лени: у функций свой `package.json`, общего пакета среди его
 * зависимостей нет, и выкладка его туда не донесёт. Меняешь сдвиг здесь —
 * меняй и там.
 *
 * Сдвиг записан числом, а не часовым поясом: Азербайджан отменил переход на
 * летнее время в 2016 году, и с тех пор это круглый год UTC+4.
 */
const BAKU_OFFSET_MS = 4 * 60 * 60 * 1000

/**
 * `null` — даты нет или она нечитаемая.
 *
 * Пустой строкой или текущим месяцем подменять нельзя: записи без `createdAt` в
 * боевой базе есть (один профиль из 134), и подмена тихо приписала бы их к
 * чужому месяцу. Вызывающий обязан показать такие отдельно.
 */
export function bakuMonth(value: string | Date | undefined | null): string | null {
  if (!value) return null
  const date = value instanceof Date ? value : new Date(value)
  const ms = date.getTime()
  if (!Number.isFinite(ms)) return null
  const shifted = new Date(ms + BAKU_OFFSET_MS)
  const month = String(shifted.getUTCMonth() + 1).padStart(2, '0')
  return `${shifted.getUTCFullYear()}-${month}`
}
